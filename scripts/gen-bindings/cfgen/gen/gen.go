func (p *Package) genAliasEnum(sb *strings.Builder, d *ir.Decl) error {
	name := p.declGoName(d)
	docComment(sb, d.Doc, name)
	fmt.Fprintf(sb, "type %s string\n\n", name)
	sb.WriteString("const (\n")
	for _, t := range d.Type.Types {
		if !t.IsStringLiteral() {
			continue
		}
		val := t.StringValue()
		constName := name + pascalCase(val)
		fmt.Fprintf(sb, "\t%s %s = %q\n", constName, name, val)
	}
	sb.WriteString(")\n\n")
	return nil
}

func (p *Package) genAliasType(sb *strings.Builder, d *ir.Decl) error {
	name := p.declGoName(d)
	conv, err := p.convFor(d.Type, p.Ov.Types[d.Name])
	if err != nil {
		return err
	}
	docComment(sb, d.Doc, name)
	fmt.Fprintf(sb, "type %s = %s\n\n", name, conv.GoType)
	return nil
}

func indentBlock(lines []string, level int) string {
	if len(lines) == 0 {
		return ""
	}
	prefix := strings.Repeat("\t", level)
	var sb strings.Builder
	for _, l := range lines {
		if l == "" {
			sb.WriteString("\n")
			continue
		}
		sb.WriteString(prefix + l + "\n")
	}
	return sb.String()
}
