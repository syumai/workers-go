// dataMembers returns the flattened property members to generate for a
// KindData/KindAliasData declaration. By the time genData is called,
// classify has already confirmed this resolves successfully (that's what
// makes it KindData/KindAliasData in the first place), so the ok result is
// not meaningful here.
func (p *Package) dataMembers(d *ir.Decl) []ir.Member {
	members, _ := resolveDataMembers(p.declByName, d)
	return members
}

func (p *Package) genData(sb *strings.Builder, d *ir.Decl) error {
	prevDeclTP := p.curDeclTypeParams
	p.curDeclTypeParams = d.TypeParams
	defer func() { p.curDeclTypeParams = prevDeclTP }()

	name := p.declGoName(d)
	members := p.dataMembers(d)

	docComment(sb, d.Doc, name)
	sb.WriteString("type " + name + " struct {\n")
	for _, m := range members {
		if m.Kind != "property" {
			continue
		}
		if p.isHandwritten(d.Name, m.Name) || p.isExcluded(d.Name, m.Name) {
			continue
		}
		fieldName := p.memberName(d.Name, m.Name)
		conv, err := p.fieldConv(d, m)
		if err != nil {
			return err
		}
		if m.Doc != "" {
			for _, l := range strings.Split(m.Doc, "\n") {
				sb.WriteString("\t// " + l + "\n")
			}
		}
		fmt.Fprintf(sb, "\t%s %s `js:%q`\n", fieldName, conv.GoType, m.Name)
	}
	sb.WriteString("}\n\n")

	if err := p.genDataFromJS(sb, d, name, members); err != nil {
		return err
	}
	if err := p.genDataToJS(sb, d, name, members); err != nil {
		return err
	}
	if p.isBinding(d.Name) {
		p.genBindingFunc(sb, d, name)
	}
	return nil
}

func (p *Package) genDataFromJS(sb *strings.Builder, d *ir.Decl, structName string, members []ir.Member) error {
	fnName := unexportedName(structName) + "FromJS"
	fmt.Fprintf(sb, "func %s(v js.Value) (%s, error) {\n\tvar out %s\n", fnName, structName, structName)
	failReturn := structName + "{}"
	for _, m := range members {
		if m.Kind != "property" {
			continue
		}
		if p.isHandwritten(d.Name, m.Name) || p.isExcluded(d.Name, m.Name) {
			continue
		}
		fieldName := p.memberName(d.Name, m.Name)
		conv, err := p.fieldConv(d, m)
		if err != nil {
			return err
		}
		jsGet := fmt.Sprintf("v.Get(%q)", m.Name)
		var block []string
		switch {
		case conv.SelfGuarded:
			// FromJS already guards null/undefined internally
			// (pointerWrap/nilGuardWrap, from fieldConv's nested-data-type
			// pointer treatment); an outer guard would just be redundant.
			block = conv.FromJS("out."+fieldName, jsGet, failReturn)
		case m.Optional || isNullableType(m.Type):
			block = append(block, "if s := "+jsGet+"; !s.IsUndefined() && !s.IsNull() {")
			block = append(block, indentAll(conv.FromJS("out."+fieldName, "s", failReturn))...)
			block = append(block, "}")
		default:
			block = conv.FromJS("out."+fieldName, jsGet, failReturn)
		}
		sb.WriteString("\t{\n")
		sb.WriteString(indentBlock(block, 2))
		sb.WriteString("\t}\n")
	}
	sb.WriteString("\treturn out, nil\n}\n\n")
	return nil
}

func (p *Package) genDataToJS(sb *strings.Builder, d *ir.Decl, structName string, members []ir.Member) error {
	p.useImport("jsrt")
	fmt.Fprintf(sb, "func (o %s) toJS() js.Value {\n\tobj := jsrt.NewObject()\n", structName)
	for _, m := range members {
		if m.Kind != "property" {
			continue
		}
		if p.isHandwritten(d.Name, m.Name) || p.isExcluded(d.Name, m.Name) {
			continue
		}
		fieldName := p.memberName(d.Name, m.Name)
		conv, err := p.fieldConv(d, m)
		if err != nil {
			return err
		}
		srcExpr := "o." + fieldName
		pre, valueExpr := conv.ToJS(srcExpr)
		cond := conv.OmitIfZero(srcExpr)
		sb.WriteString("\tif " + cond + " {\n")
		sb.WriteString(indentBlock(pre, 2))
		fmt.Fprintf(sb, "\t\tobj.Set(%q, %s)\n", m.Name, valueExpr)
		sb.WriteString("\t}\n")
	}
	sb.WriteString("\treturn obj\n}\n\n")
	return nil
}

