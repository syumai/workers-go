// handle types
// ---------------------------------------------------------------------------

type memberGroup struct {
	Kind    string
	Name    string
	Members []ir.Member
}

func groupMembers(members []ir.Member) []memberGroup {
	var groups []memberGroup
	index := map[string]int{}
	for _, m := range members {
		if m.Kind != "method" {
			groups = append(groups, memberGroup{Kind: m.Kind, Name: m.Name, Members: []ir.Member{m}})
			continue
		}
		key := "method:" + m.Name
		if i, ok := index[key]; ok {
			groups[i].Members = append(groups[i].Members, m)
			continue
		}
		index[key] = len(groups)
		groups = append(groups, memberGroup{Kind: "method", Name: m.Name, Members: []ir.Member{m}})
	}
	return groups
}

func (p *Package) genHandle(sb *strings.Builder, d *ir.Decl) error {
	name := p.declGoName(d)
	docComment(sb, d.Doc, name)
	fmt.Fprintf(sb, "type %s struct{ v js.Value }\n\n", name)

	fmt.Fprintf(sb, "// %sFromJS wraps a JS %s value.\nfunc %sFromJS(v js.Value) *%s { return &%s{v: v} }\n\n",
		name, name, name, name, name)
	fmt.Fprintf(sb, "// JSValue returns the underlying JS value.\nfunc (x *%s) JSValue() js.Value { return x.v }\n\n", name)

	if p.isBinding(d.Name) {
		p.genBindingFunc(sb, d, name)
	}

	prevDeclTP := p.curDeclTypeParams
	p.curDeclTypeParams = d.TypeParams
	defer func() { p.curDeclTypeParams = prevDeclTP }()

	// resolveHandleMembers pulls in getters/methods a handle inherits from
	// an extends ancestor that's also handle-shaped (e.g. R2ObjectBody
	// extends R2Object); see tmp/06-codegen-spec.md 2.1 item 4.
	for _, g := range groupMembers(resolveHandleMembers(p.declByName, d, 0)) {
		if p.isHandwritten(d.Name, g.Name) || p.isExcluded(d.Name, g.Name) {
			continue
		}
		switch g.Kind {
		case "property", "getter":
			if err := p.genGetter(sb, d, name, g.Members[0]); err != nil {
				return err
			}
		case "method":
			if err := p.genMethodGroup(sb, d, name, g.Members); err != nil {
				return err
			}
		}
	}
	return nil
}

func (p *Package) genBindingFunc(sb *strings.Builder, d *ir.Decl, name string) {
	p.useImport("jsrt")
	switch classify(p.declByName, d) {
	case KindHandle:
		fmt.Fprintf(sb, "// New%s resolves the binding named bindingName from env.\n", name)
		fmt.Fprintf(sb, "func New%s(bindingName string) (*%s, error) {\n", name, name)
		sb.WriteString("\tv, err := jsrt.Binding(bindingName)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(sb, "\treturn &%s{v: v}, nil\n}\n\n", name)
	default:
		fromJSFunc := unexportedName(name) + "FromJS"
		fmt.Fprintf(sb, "// New%s resolves the binding named bindingName from env.\n", name)
		fmt.Fprintf(sb, "func New%s(bindingName string) (%s, error) {\n", name, name)
		fmt.Fprintf(sb, "\tv, err := jsrt.Binding(bindingName)\n\tif err != nil {\n\t\treturn %s{}, err\n\t}\n", name)
		fmt.Fprintf(sb, "\treturn %s(v)\n}\n\n", fromJSFunc)
	}
}

func (p *Package) genGetter(sb *strings.Builder, d *ir.Decl, structName string, m ir.Member) error {
	goName := p.memberName(d.Name, m.Name)
	override := p.typeOverride(d.Name, m.Name, "")
	t := m.Type
	prevMember := p.curMemberName
	p.curMemberName = m.Name
	p.resetNotes()
	conv, err := p.convForNamed(t, override, structName+goName)
	notes := p.takeNotes()
	p.curMemberName = prevMember
	if err != nil {
		return err
	}
	docComment(sb, appendNotesToDoc(m.Doc, notes), goName)
	fmt.Fprintf(sb, "func (x *%s) %s() %s {\n", structName, goName, conv.GoType)
	src := fmt.Sprintf("x.v.Get(%q)", m.Name)
	sb.WriteString("\tvar ret " + conv.GoType + "\n")
	// A getter's enclosing function returns a single value, so pass "" as
	// FromJS's failReturn: there's nowhere to propagate a decode error to
	// (see the KindData/KindAliasData case in declRefConv).
	if m.Optional || isNullableType(t) {
		sb.WriteString("\tif s := " + src + "; !s.IsUndefined() && !s.IsNull() {\n")
		sb.WriteString(indentBlock(conv.FromJS("ret", "s", ""), 2))
		sb.WriteString("\t}\n")
	} else {
		sb.WriteString(indentBlock(conv.FromJS("ret", src, ""), 1))
	}
	sb.WriteString("\treturn ret\n}\n\n")
	return nil
}

// genMethodGroup emits Go methods for one same-named group of members. A
// non-overloaded member (the common case) is emitted as-is. An overloaded
// one (len(members) > 1) requires an "overloads:" entry per
// tmp/06-codegen-spec.md 2.1 item 1: each configured entry names one
// overload (by its 0-based position within this group) to generate under a
// distinct Go name, optionally dropping a literal-typed discriminant
// parameter (e.g. `type: "text"`) from the Go signature and passing it as a
// constant instead. Overloads with no matching entry are skipped, with a
// warning.
func (p *Package) genMethodGroup(sb *strings.Builder, d *ir.Decl, structName string, members []ir.Member) error {
	prevMember := p.curMemberName
	p.curMemberName = members[0].Name
	defer func() { p.curMemberName = prevMember }()

	if len(members) == 1 {
		goName := p.memberName(d.Name, members[0].Name)
		return p.genMethod(sb, d, structName, members[0], goName, -1, "")
	}
	key := memberKey(d.Name, members[0].Name)
	entries, ok := p.Ov.Overloads[key]
	if !ok {
		return fmt.Errorf("%s has %d overloads but no overloads rule is configured in overrides", key, len(members))
	}
	handled := make([]bool, len(members))
	for _, e := range entries {
		if e.Index < 0 || e.Index >= len(members) {
			return fmt.Errorf("%s: overloads: index %d out of range (method has %d overloads)", key, e.Index, len(members))
		}
		if handled[e.Index] {
			return fmt.Errorf("%s: overloads: index %d configured more than once", key, e.Index)
		}
		handled[e.Index] = true
		m := members[e.Index]
		dropIdx, dropExpr := -1, ""
		if e.Literal != "" {
			found := false
			for pi, prm := range m.Params {
				if prm.Type != nil && prm.Type.IsStringLiteral() && prm.Type.StringValue() == e.Literal {
					dropIdx, dropExpr, found = pi, fmt.Sprintf("%q", e.Literal), true
					break
				}
			}
			if !found {
				return fmt.Errorf("%s: overloads: index %d has no parameter of literal type %q (has the upstream overload order changed?)", key, e.Index, e.Literal)
			}
		}
		if err := p.genMethod(sb, d, structName, m, exportedName(e.Name), dropIdx, dropExpr); err != nil {
			return err
		}
	}
	for i, m := range members {
		if !handled[i] {
			p.warnf("%s: skipping overload %d (%d params) with no overloads: entry", key, i, len(m.Params))
		}
	}
	return nil
}

// genMethod emits one Go method for member m. If dropIdx >= 0, m.Params[dropIdx]
// (a literal-typed discriminant parameter from an overload split; see
// genMethodGroup) is omitted from the Go signature and dropExpr — a Go
// constant expression — is passed in its place at the call site.
func (p *Package) genMethod(sb *strings.Builder, d *ir.Decl, structName string, m ir.Member, goName string, dropIdx int, dropExpr string) error {
	// tmp/06-codegen-spec.md 5.1 item 5: a method whose only parameter is
	// a callback of shape "(a: A) => Promise<U>" / "() => Promise<U>"
	// gets a dedicated Go signature (func(*A) (U, error) etc.) instead of
	// falling back to js.Value for the unsupported function-typed param.
	// Not applicable when genMethodGroup is dropping a literal
	// discriminant parameter (dropIdx >= 0): no currently generated
	// overloaded method has this shape.
	if dropIdx < 0 {
		if fn, ok := detectCallbackMethod(m); ok {
			return p.genCallbackMethod(sb, d, structName, m, goName, fn)
		}
	}

	prevMethodTP := p.curMethodTypeParams
	p.curMethodTypeParams = m.TypeParams
	defer func() { p.curMethodTypeParams = prevMethodTP }()

	p.resetNotes()
	methodHint := structName + goName

	var params []string
	var argExprs []string
	var argBlocks [][]string
	// restExpr, if non-empty, is a Go slice expression (the rest parameter
	// itself, or a built []any) spread as the final jsrt.Call argument via
	// "restExpr...". Set by the ir.Param.Rest case below; per
	// tmp/06-codegen-spec.md 4.1, a rest parameter (always last, per JS/TS
	// syntax) becomes a Go variadic parameter instead of a single []T one.
	var restExpr string
	for i, prm := range m.Params {
		if i == dropIdx {
			argExprs = append(argExprs, dropExpr)
			continue
		}
		if prm.Rest {
			pname := p.paramGoName(d.Name, m.Name, prm.Name)
			elemType := prm.Type
			if elemType != nil && elemType.K == "array" {
				elemType = elemType.Elem
			}
			elemConv, err := p.convForParam(elemType, "", methodHint+exportedName(pname))
			if err != nil {
				return err
			}
			if elemConv.GoType == "js.Value" {
				// An element that itself maps to a raw js.Value (e.g. the
				// bindings ...any of SqlStorage.exec) is instead given the
				// Go type any: jsrt.Call already takes ...any, so the
				// variadic parameter spreads straight through with no
				// per-element conversion, and callers can pass plain Go
				// values (js.ValueOf handles those) instead of having to
				// wrap each one as a js.Value themselves.
				params = append(params, pname+" ...any")
				restExpr = pname
				continue
			}
			params = append(params, pname+" ..."+elemConv.GoType)
			argVar := fmt.Sprintf("arg%d", i)
			pre, expr := elemConv.ToJS("e")
			block := []string{
				argVar + " := make([]any, len(" + pname + "))",
				"for i, e := range " + pname + " {",
			}
			block = append(block, indentAll(pre)...)
			block = append(block, "\t"+argVar+"[i] = "+expr, "}")
			argBlocks = append(argBlocks, block)
			restExpr = argVar
			continue
		}
		pname := p.paramGoName(d.Name, m.Name, prm.Name)
		override := p.typeOverride(d.Name, m.Name, "params."+prm.Name)
		conv, err := p.convForParam(prm.Type, override, methodHint+exportedName(pname))
		if err != nil {
			return err
		}
		params = append(params, pname+" "+conv.GoType)
		pre, expr := conv.ToJS(pname)
		if len(pre) == 0 {
			argExprs = append(argExprs, expr)
			continue
		}
		// A multi-statement JS conversion (e.g. building a JS Array or
		// object from a Go slice/map) can't be inlined as a single call
		// argument expression. Every ToJS implementation that emits
		// pre-statements today (array, record, map[string]any) computes
		// its result as a js.Value, so it's always valid to spill it into
		// a js.Value local — scoped to its own block so distinct params
		// reusing the same conversion (and its internal names like "arr")
		// don't collide.
		argVar := fmt.Sprintf("arg%d", i)
		block := []string{"var " + argVar + " js.Value", "{"}
		block = append(block, indentAll(pre)...)
		block = append(block, "\t"+argVar+" = "+expr, "}")
		argBlocks = append(argBlocks, block)
		argExprs = append(argExprs, argVar)
	}

	ret := m.Returns
	isAsync := ret != nil && ret.K == "ref" && ret.Name == "Promise"
	var innerType *ir.Type
	if isAsync {
		if len(ret.Args) > 0 {
			innerType = &ret.Args[0]
		} else {
			innerType = &ir.Type{K: "prim", Name: "void"}
		}
	} else {
		innerType = ret
	}
	isVoid := innerType == nil || (innerType.K == "prim" && innerType.Name == "void")

	// The return type's own conversion is resolved here, ahead of
	// docComment below, purely so that any notef notes it raises (e.g.
	// the single-included-ref-union rule) land in pendingNotes before
	// takeNotes drains them into the emitted doc comment — the actual use
	// of conv/nullable is unchanged from before this reordering.
	var conv exprConv
	var nullable bool
	if !isVoid {
		retOverride := p.typeOverride(d.Name, m.Name, "returns")
		// tmp/06-codegen-spec.md 2.1 item 3: Promise<T | null/undefined>
		// (T a prim, handle, or data type) becomes (*T, error) rather
		// than silently collapsing null to T's zero value. An explicit
		// types: override always wins (the author has already chosen the
		// exact Go type/behavior).
		nonNullType := innerType
		if retOverride == "" {
			nonNullType, nullable = splitNullable(innerType)
		}
		var err error
		conv, err = p.convForNamed(nonNullType, retOverride, methodHint)
		if err != nil {
			return err
		}
		if nullable {
			conv = p.nullableReturnConv(conv)
		}
	}

	p.useImport("jsrt")
	doc := appendNotesToDoc(m.Doc, p.takeNotes())
	docComment(sb, doc, goName)

	callArgs := "x.v, " + fmt.Sprintf("%q", m.Name)
	switch {
	case restExpr != "" && len(argExprs) > 0:
		// jsrt.Call(v, method, args ...any) has exactly one variadic
		// parameter, and Go doesn't allow mixing individually-listed
		// arguments with a trailing spread for the same variadic parameter
		// (e.g. "f(x, y, s...)" is invalid when x/y would otherwise need to
		// land in the same ...T as s) — so when a rest parameter's own Go
		// method also has ordinary leading parameters (e.g.
		// SqlStorage.Exec(query string, bindings ...any)), fold them into
		// one []any ahead of the rest slice instead.
		callArgs += ", append([]any{" + strings.Join(argExprs, ", ") + "}, " + restExpr + "...)..."
	case restExpr != "":
		callArgs += ", " + restExpr + "..."
	case len(argExprs) > 0:
		callArgs += ", " + strings.Join(argExprs, ", ")
	}

	if isVoid {
		fmt.Fprintf(sb, "func (x *%s) %s(%s) error {\n", structName, goName, strings.Join(params, ", "))
		for _, b := range argBlocks {
			sb.WriteString(indentBlock(b, 1))
		}
		if isAsync {
			sb.WriteString("\tp, err := jsrt.Call(" + callArgs + ")\n\tif err != nil {\n\t\treturn err\n\t}\n\t_, err = jsrt.Await(p)\n\treturn err\n")
		} else {
			sb.WriteString("\t_, err := jsrt.Call(" + callArgs + ")\n\treturn err\n")
		}
		sb.WriteString("}\n\n")
		return nil
	}

	fmt.Fprintf(sb, "func (x *%s) %s(%s) (%s, error) {\n", structName, goName, strings.Join(params, ", "), conv.GoType)
	for _, b := range argBlocks {
		sb.WriteString(indentBlock(b, 1))
	}
	if isAsync {
		fmt.Fprintf(sb, "\tp, err := jsrt.Call(%s)\n\tif err != nil {\n\t\treturn %s, err\n\t}\n", callArgs, conv.ZeroExpr)
		sb.WriteString("\tr, err := jsrt.Await(p)\n\tif err != nil {\n\t\treturn " + conv.ZeroExpr + ", err\n\t}\n")
	} else {
		fmt.Fprintf(sb, "\tr, err := jsrt.Call(%s)\n\tif err != nil {\n\t\treturn %s, err\n\t}\n", callArgs, conv.ZeroExpr)
	}
	sb.WriteString("\tvar ret " + conv.GoType + "\n")
	sb.WriteString(indentBlock(conv.FromJS("ret", "r", conv.ZeroExpr), 1))
	sb.WriteString("\treturn ret, nil\n}\n\n")
	return nil
}

// detectCallbackMethod reports whether m's single parameter is a callback
// of shape "(a: A) => Promise<U>" or "() => Promise<U>" — the case
// genCallbackMethod generates a dedicated Go signature for, per
// tmp/06-codegen-spec.md 5.1 item 5. On success it returns the callback's
// own function type (m.Params[0].Type); its Params has 0 or 1 entries and
// its Returns is always a Promise ref.
func detectCallbackMethod(m ir.Member) (*ir.Type, bool) {
	if len(m.Params) != 1 {
		return nil, false
	}
	prm := m.Params[0]
	if prm.Rest || prm.Type == nil || prm.Type.K != "function" {
		return nil, false
	}
	fn := prm.Type
	if len(fn.Params) > 1 {
		return nil, false
	}
	if fn.Returns == nil || fn.Returns.K != "ref" || fn.Returns.Name != "Promise" {
		return nil, false
	}
	return fn, true
}

// genCallbackMethod emits one Go method for a member matched by
// detectCallbackMethod: a callback parameter "func(a: A) => Promise<U>" (or
// "() => Promise<U>") becomes a Go func(*A) (U, error) (or func() (U,
// error); U void drops the U and becomes just func(...) error) parameter.
// The generated body wraps the Go closure as a JS function via
// jsrt.AsyncFunc (releasing it once the outer JS call has settled) — see
// tmp/06-codegen-spec.md 5.1 item 5. The outer method's own return type is
// assumed to mirror the callback's (Promise<T> in both places, as in every
// currently generated case — DurableObjectStorage.transaction and
// DurableObjectState.blockConcurrencyWhile both return Promise<T> for the
// same T their callback returns); a hypothetical future case where they
// differ isn't specially detected, since none exists in the packages cfgen
// currently generates.
func (p *Package) genCallbackMethod(sb *strings.Builder, d *ir.Decl, structName string, m ir.Member, goName string, fn *ir.Type) error {
	prevMethodTP := p.curMethodTypeParams
	p.curMethodTypeParams = m.TypeParams
	defer func() { p.curMethodTypeParams = prevMethodTP }()

	hint := structName + goName
	hasArg := len(fn.Params) == 1
	var argConv exprConv
	if hasArg {
		var err error
		argConv, err = p.convForNamed(fn.Params[0].Type, "", hint+"Arg")
		if err != nil {
			return err
		}
	}

	var innerType *ir.Type
	if len(fn.Returns.Args) > 0 {
		innerType = &fn.Returns.Args[0]
	} else {
		innerType = &ir.Type{K: "prim", Name: "void"}
	}
	isVoid := innerType.K == "prim" && innerType.Name == "void"
	var retConv exprConv
	if !isVoid {
		var err error
		retConv, err = p.convForParam(innerType, "", hint+"Result")
		if err != nil {
			return err
		}
	}

	var cbGoType string
	switch {
	case hasArg && !isVoid:
		cbGoType = "func(" + argConv.GoType + ") (" + retConv.GoType + ", error)"
	case hasArg:
		cbGoType = "func(" + argConv.GoType + ") error"
	case !isVoid:
		cbGoType = "func() (" + retConv.GoType + ", error)"
	default:
		cbGoType = "func() error"
	}

	p.useImport("jsrt")
	docComment(sb, m.Doc, goName)

	cbParamName := goParamName(m.Params[0].Name)
	isAsync := m.Returns != nil && m.Returns.K == "ref" && m.Returns.Name == "Promise"

	if isVoid {
		fmt.Fprintf(sb, "func (x *%s) %s(%s %s) error {\n", structName, goName, cbParamName, cbGoType)
	} else {
		fmt.Fprintf(sb, "func (x *%s) %s(%s %s) (%s, error) {\n", structName, goName, cbParamName, cbGoType, retConv.GoType)
	}

	sb.WriteString("\tcb := jsrt.AsyncFunc(func(cbArgs []js.Value) (js.Value, error) {\n")
	if hasArg {
		sb.WriteString("\t\tvar a0 " + argConv.GoType + "\n")
		sb.WriteString(indentBlock(argConv.FromJS("a0", "cbArgs[0]", "js.Value{}"), 2))
	}
	switch {
	case hasArg && !isVoid:
		sb.WriteString("\t\tresult, err := " + cbParamName + "(a0)\n")
	case hasArg:
		sb.WriteString("\t\terr := " + cbParamName + "(a0)\n")
	case !isVoid:
		sb.WriteString("\t\tresult, err := " + cbParamName + "()\n")
	default:
		sb.WriteString("\t\terr := " + cbParamName + "()\n")
	}
	sb.WriteString("\t\tif err != nil {\n\t\t\treturn js.Value{}, err\n\t\t}\n")
	if isVoid {
		sb.WriteString("\t\treturn js.Undefined(), nil\n")
	} else {
		pre, expr := retConv.ToJS("result")
		sb.WriteString(indentBlock(pre, 2))
		sb.WriteString("\t\treturn " + expr + ", nil\n")
	}
	sb.WriteString("\t})\n")
	sb.WriteString("\tdefer cb.Release()\n")

	callArgs := fmt.Sprintf("x.v, %q, cb", m.Name)
	if isVoid {
		if isAsync {
			sb.WriteString("\tp, err := jsrt.Call(" + callArgs + ")\n\tif err != nil {\n\t\treturn err\n\t}\n\t_, err = jsrt.Await(p)\n\treturn err\n")
		} else {
			sb.WriteString("\t_, err := jsrt.Call(" + callArgs + ")\n\treturn err\n")
		}
		sb.WriteString("}\n\n")
		return nil
	}
	if isAsync {
		fmt.Fprintf(sb, "\tp, err := jsrt.Call(%s)\n\tif err != nil {\n\t\treturn %s, err\n\t}\n", callArgs, retConv.ZeroExpr)
		sb.WriteString("\tr, err := jsrt.Await(p)\n\tif err != nil {\n\t\treturn " + retConv.ZeroExpr + ", err\n\t}\n")
	} else {
		fmt.Fprintf(sb, "\tr, err := jsrt.Call(%s)\n\tif err != nil {\n\t\treturn %s, err\n\t}\n", callArgs, retConv.ZeroExpr)
	}
	sb.WriteString("\tvar ret " + retConv.GoType + "\n")
	sb.WriteString(indentBlock(retConv.FromJS("ret", "r", retConv.ZeroExpr), 1))
	sb.WriteString("\treturn ret, nil\n}\n\n")
	return nil
}

func goParamName(name string) string {
	n := name
	if goKeywords[n] {
		n += "_"
	}
	return n
}

