// Package gen implements the IR-to-Go code generator used by cfgen. It
// reads a package's overrides YAML plus the shared IR, classifies each
// included declaration (handle / data / alias), and emits a single
// z<pkg>_gen.go file.
package gen

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/syumai/workers-go/scripts/gen-bindings/cfgen/ir"
)

// Result is the outcome of generating one package.
type Result struct {
	Source   []byte
	Warnings []string
}

// Generate produces the formatted Go source for ov, using doc as the
// shared IR.
func Generate(doc *ir.IR, ov *Overrides) (*Result, error) {
	p := NewPackage(doc, ov)

	var body strings.Builder
	for _, name := range ov.Include {
		d, ok := p.included[name]
		if !ok {
			return nil, fmt.Errorf("include: declaration %q not found", name)
		}
		if err := p.genDecl(&body, d); err != nil {
			return nil, fmt.Errorf("%s: %w", d.Name, err)
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by cfgen from %s@%s. DO NOT EDIT.\n\n", doc.Source.Package, doc.Source.Version)
	out.WriteString("//go:build js && wasm\n\n")
	if ov.Doc != "" {
		for _, l := range strings.Split(strings.TrimRight(ov.Doc, "\n"), "\n") {
			if l == "" {
				out.WriteString("//\n")
			} else {
				out.WriteString("// " + l + "\n")
			}
		}
	}
	fmt.Fprintf(&out, "package %s\n\n", ov.Package)

	writeImports(&out, p.imports)

	out.WriteString(body.String())

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w\n---\n%s", err, out.String())
	}
	return &Result{Source: formatted, Warnings: p.warnings}, nil
}

func writeImports(out *strings.Builder, imports map[string]bool) {
	var std []string
	const jsrtPath = "github.com/syumai/workers-go/exp/internal/jsrt"
	for path := range imports {
		if path == "jsrt" {
			continue
		}
		std = append(std, path)
	}
	sort.Strings(std)
	std = append([]string{"syscall/js"}, std...)

	out.WriteString("import (\n")
	for _, p := range std {
		fmt.Fprintf(out, "\t%q\n", p)
	}
	if imports["jsrt"] {
		out.WriteString("\n")
		fmt.Fprintf(out, "\t%q\n", jsrtPath)
	}
	out.WriteString(")\n\n")
}

func (p *Package) genDecl(sb *strings.Builder, d *ir.Decl) error {
	switch classify(p.declByName, d) {
	case KindHandle:
		return p.genHandle(sb, d)
	case KindData, KindAliasData:
		return p.genData(sb, d)
	case KindAliasEnum:
		return p.genAliasEnum(sb, d)
	case KindAliasType:
		return p.genAliasType(sb, d)
	}
	return fmt.Errorf("unhandled decl kind for %q", d.Name)
}

func docComment(sb *strings.Builder, doc, name string) {
	if doc == "" {
		fmt.Fprintf(sb, "// %s\n", name)
		return
	}
	lines := strings.Split(doc, "\n")
	fmt.Fprintf(sb, "// %s %s\n", name, lines[0])
	for _, l := range lines[1:] {
		if l == "" {
			sb.WriteString("//\n")
		} else {
			fmt.Fprintf(sb, "// %s\n", l)
		}
	}
}

// ---------------------------------------------------------------------------
// handle types
// ---------------------------------------------------------------------------

type memberGroup struct {
	Kind    string
	Name    string
	Members []ir.Member
}

func groupMembers(members []ir.Member) []memberGroup {
	var groups []memberGroup
	index := map[string]int{}
	for _, m := range members {
		if m.Kind != "method" {
			groups = append(groups, memberGroup{Kind: m.Kind, Name: m.Name, Members: []ir.Member{m}})
			continue
		}
		key := "method:" + m.Name
		if i, ok := index[key]; ok {
			groups[i].Members = append(groups[i].Members, m)
			continue
		}
		index[key] = len(groups)
		groups = append(groups, memberGroup{Kind: "method", Name: m.Name, Members: []ir.Member{m}})
	}
	return groups
}

func (p *Package) genHandle(sb *strings.Builder, d *ir.Decl) error {
	name := p.declGoName(d)
	docComment(sb, d.Doc, name)
	fmt.Fprintf(sb, "type %s struct{ v js.Value }\n\n", name)

	fmt.Fprintf(sb, "// %sFromJS wraps a JS %s value.\nfunc %sFromJS(v js.Value) *%s { return &%s{v: v} }\n\n",
		name, name, name, name, name)
	fmt.Fprintf(sb, "// JSValue returns the underlying JS value.\nfunc (x *%s) JSValue() js.Value { return x.v }\n\n", name)

	if p.isBinding(d.Name) {
		p.genBindingFunc(sb, d, name)
	}

	prevDeclTP := p.curDeclTypeParams
	p.curDeclTypeParams = d.TypeParams
	defer func() { p.curDeclTypeParams = prevDeclTP }()

	// resolveHandleMembers pulls in getters/methods a handle inherits from
	// an extends ancestor that's also handle-shaped (e.g. R2ObjectBody
	// extends R2Object); see tmp/06-codegen-spec.md 2.1 item 4.
	for _, g := range groupMembers(resolveHandleMembers(p.declByName, d, 0)) {
		if p.isHandwritten(d.Name, g.Name) || p.isExcluded(d.Name, g.Name) {
			continue
		}
		switch g.Kind {
		case "property", "getter":
			if err := p.genGetter(sb, d, name, g.Members[0]); err != nil {
				return err
			}
		case "method":
			if err := p.genMethodGroup(sb, d, name, g.Members); err != nil {
				return err
			}
		}
	}
	return nil
}

func (p *Package) genBindingFunc(sb *strings.Builder, d *ir.Decl, name string) {
	p.useImport("jsrt")
	switch classify(p.declByName, d) {
	case KindHandle:
		fmt.Fprintf(sb, "// New%s resolves the binding named bindingName from env.\n", name)
		fmt.Fprintf(sb, "func New%s(bindingName string) (*%s, error) {\n", name, name)
		sb.WriteString("\tv, err := jsrt.Binding(bindingName)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(sb, "\treturn &%s{v: v}, nil\n}\n\n", name)
	default:
		fromJSFunc := unexportedName(name) + "FromJS"
		fmt.Fprintf(sb, "// New%s resolves the binding named bindingName from env.\n", name)
		fmt.Fprintf(sb, "func New%s(bindingName string) (%s, error) {\n", name, name)
		fmt.Fprintf(sb, "\tv, err := jsrt.Binding(bindingName)\n\tif err != nil {\n\t\treturn %s{}, err\n\t}\n", name)
		fmt.Fprintf(sb, "\treturn %s(v)\n}\n\n", fromJSFunc)
	}
}

func (p *Package) genGetter(sb *strings.Builder, d *ir.Decl, structName string, m ir.Member) error {
	goName := p.memberName(d.Name, m.Name)
	override := p.typeOverride(d.Name, m.Name, "")
	t := m.Type
	conv, err := p.convFor(t, override)
	if err != nil {
		return err
	}
	docComment(sb, m.Doc, goName)
	fmt.Fprintf(sb, "func (x *%s) %s() %s {\n", structName, goName, conv.GoType)
	src := fmt.Sprintf("x.v.Get(%q)", m.Name)
	sb.WriteString("\tvar ret " + conv.GoType + "\n")
	// A getter's enclosing function returns a single value, so pass "" as
	// FromJS's failReturn: there's nowhere to propagate a decode error to
	// (see the KindData/KindAliasData case in declRefConv).
	if m.Optional || isNullableType(t) {
		sb.WriteString("\tif s := " + src + "; !s.IsUndefined() && !s.IsNull() {\n")
		sb.WriteString(indentBlock(conv.FromJS("ret", "s", ""), 2))
		sb.WriteString("\t}\n")
	} else {
		sb.WriteString(indentBlock(conv.FromJS("ret", src, ""), 1))
	}
	sb.WriteString("\treturn ret\n}\n\n")
	return nil
}

// genMethodGroup emits Go methods for one same-named group of members. A
// non-overloaded member (the common case) is emitted as-is. An overloaded
// one (len(members) > 1) requires an "overloads:" entry per
// tmp/06-codegen-spec.md 2.1 item 1: each configured entry names one
// overload (by its 0-based position within this group) to generate under a
// distinct Go name, optionally dropping a literal-typed discriminant
// parameter (e.g. `type: "text"`) from the Go signature and passing it as a
// constant instead. Overloads with no matching entry are skipped, with a
// warning.
func (p *Package) genMethodGroup(sb *strings.Builder, d *ir.Decl, structName string, members []ir.Member) error {
	if len(members) == 1 {
		goName := p.memberName(d.Name, members[0].Name)
		return p.genMethod(sb, d, structName, members[0], goName, -1, "")
	}
	key := memberKey(d.Name, members[0].Name)
	entries, ok := p.Ov.Overloads[key]
	if !ok {
		return fmt.Errorf("%s has %d overloads but no overloads rule is configured in overrides", key, len(members))
	}
	handled := make([]bool, len(members))
	for _, e := range entries {
		if e.Index < 0 || e.Index >= len(members) {
			return fmt.Errorf("%s: overloads: index %d out of range (method has %d overloads)", key, e.Index, len(members))
		}
		if handled[e.Index] {
			return fmt.Errorf("%s: overloads: index %d configured more than once", key, e.Index)
		}
		handled[e.Index] = true
		m := members[e.Index]
		dropIdx, dropExpr := -1, ""
		if e.Literal != "" {
			found := false
			for pi, prm := range m.Params {
				if prm.Type != nil && prm.Type.IsStringLiteral() && prm.Type.StringValue() == e.Literal {
					dropIdx, dropExpr, found = pi, fmt.Sprintf("%q", e.Literal), true
					break
				}
			}
			if !found {
				return fmt.Errorf("%s: overloads: index %d has no parameter of literal type %q (has the upstream overload order changed?)", key, e.Index, e.Literal)
			}
		}
		if err := p.genMethod(sb, d, structName, m, exportedName(e.Name), dropIdx, dropExpr); err != nil {
			return err
		}
	}
	for i, m := range members {
		if !handled[i] {
			p.warnf("%s: skipping overload %d (%d params) with no overloads: entry", key, i, len(m.Params))
		}
	}
	return nil
}

// genMethod emits one Go method for member m. If dropIdx >= 0, m.Params[dropIdx]
// (a literal-typed discriminant parameter from an overload split; see
// genMethodGroup) is omitted from the Go signature and dropExpr — a Go
// constant expression — is passed in its place at the call site.
func (p *Package) genMethod(sb *strings.Builder, d *ir.Decl, structName string, m ir.Member, goName string, dropIdx int, dropExpr string) error {
	prevMethodTP := p.curMethodTypeParams
	p.curMethodTypeParams = m.TypeParams
	defer func() { p.curMethodTypeParams = prevMethodTP }()

	var params []string
	var argExprs []string
	var argBlocks [][]string
	for i, prm := range m.Params {
		if i == dropIdx {
			argExprs = append(argExprs, dropExpr)
			continue
		}
		pname := goParamName(prm.Name)
		override := p.typeOverride(d.Name, m.Name, "params."+prm.Name)
		conv, err := p.convFor(prm.Type, override)
		if err != nil {
			return err
		}
		params = append(params, pname+" "+conv.GoType)
		pre, expr := conv.ToJS(pname)
		if len(pre) == 0 {
			argExprs = append(argExprs, expr)
			continue
		}
		// A multi-statement JS conversion (e.g. building a JS Array or
		// object from a Go slice/map) can't be inlined as a single call
		// argument expression. Every ToJS implementation that emits
		// pre-statements today (array, record, map[string]any) computes
		// its result as a js.Value, so it's always valid to spill it into
		// a js.Value local — scoped to its own block so distinct params
		// reusing the same conversion (and its internal names like "arr")
		// don't collide.
		argVar := fmt.Sprintf("arg%d", i)
		block := []string{"var " + argVar + " js.Value", "{"}
		block = append(block, indentAll(pre)...)
		block = append(block, "\t"+argVar+" = "+expr, "}")
		argBlocks = append(argBlocks, block)
		argExprs = append(argExprs, argVar)
	}

	ret := m.Returns
	isAsync := ret != nil && ret.K == "ref" && ret.Name == "Promise"
	var innerType *ir.Type
	if isAsync {
		if len(ret.Args) > 0 {
			innerType = &ret.Args[0]
		} else {
			innerType = &ir.Type{K: "prim", Name: "void"}
		}
	} else {
		innerType = ret
	}
	isVoid := innerType == nil || (innerType.K == "prim" && innerType.Name == "void")

	p.useImport("jsrt")
	docComment(sb, m.Doc, goName)

	callArgs := "x.v, " + fmt.Sprintf("%q", m.Name)
	if len(argExprs) > 0 {
		callArgs += ", " + strings.Join(argExprs, ", ")
	}

	if isVoid {
		fmt.Fprintf(sb, "func (x *%s) %s(%s) error {\n", structName, goName, strings.Join(params, ", "))
		for _, b := range argBlocks {
			sb.WriteString(indentBlock(b, 1))
		}
		if isAsync {
			sb.WriteString("\tp, err := jsrt.Call(" + callArgs + ")\n\tif err != nil {\n\t\treturn err\n\t}\n\t_, err = jsrt.Await(p)\n\treturn err\n")
		} else {
			sb.WriteString("\t_, err := jsrt.Call(" + callArgs + ")\n\treturn err\n")
		}
		sb.WriteString("}\n\n")
		return nil
	}

	retOverride := p.typeOverride(d.Name, m.Name, "returns")
	// tmp/06-codegen-spec.md 2.1 item 3: Promise<T | null/undefined> (T a
	// prim, handle, or data type) becomes (*T, error) rather than silently
	// collapsing null to T's zero value. An explicit types: override always
	// wins (the author has already chosen the exact Go type/behavior).
	nonNullType, nullable := innerType, false
	if retOverride == "" {
		nonNullType, nullable = splitNullable(innerType)
	}
	conv, err := p.convFor(nonNullType, retOverride)
	if err != nil {
		return err
	}
	if nullable {
		conv = p.nullableReturnConv(conv)
	}
	fmt.Fprintf(sb, "func (x *%s) %s(%s) (%s, error) {\n", structName, goName, strings.Join(params, ", "), conv.GoType)
	for _, b := range argBlocks {
		sb.WriteString(indentBlock(b, 1))
	}
	if isAsync {
		fmt.Fprintf(sb, "\tp, err := jsrt.Call(%s)\n\tif err != nil {\n\t\treturn %s, err\n\t}\n", callArgs, conv.ZeroExpr)
		sb.WriteString("\tr, err := jsrt.Await(p)\n\tif err != nil {\n\t\treturn " + conv.ZeroExpr + ", err\n\t}\n")
	} else {
		fmt.Fprintf(sb, "\tr, err := jsrt.Call(%s)\n\tif err != nil {\n\t\treturn %s, err\n\t}\n", callArgs, conv.ZeroExpr)
	}
	sb.WriteString("\tvar ret " + conv.GoType + "\n")
	sb.WriteString(indentBlock(conv.FromJS("ret", "r", conv.ZeroExpr), 1))
	sb.WriteString("\treturn ret, nil\n}\n\n")
	return nil
}

func goParamName(name string) string {
	n := name
	if goKeywords[n] {
		n += "_"
	}
	return n
}

